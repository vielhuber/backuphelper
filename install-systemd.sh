#!/usr/bin/env bash
set -euo pipefail
shopt -s nullglob

SCRIPT_DIR="$(cd "$(dirname "$(readlink -f "$0")")" && pwd)"
CONFIG="$SCRIPT_DIR/config.yaml"
RUN_AS=$(id -un)
while (($#)); do
    case "$1" in
        --config)
            CONFIG=${2:?--config needs a file}
            shift 2
            ;;
        --user)
            RUN_AS=${2:?--user needs a user}
            shift 2
            ;;
        --)
            shift
            break
            ;;
        *)
            echo 'usage: install-systemd.sh [--config file] [--user user] [-- command ...]' >&2
            exit 2
            ;;
    esac
done
id "$RUN_AS" > /dev/null
if [[ $CONFIG != /* ]]; then CONFIG="$PWD/$CONFIG"; fi
[[ -f $CONFIG ]] || {
    echo 'Config file is missing.' >&2
    exit 1
}
SETTINGS=$(yq -c . "$CONFIG")
mapfile -t JOBS < <(jq -r '. // {} | keys_unsorted[]' <<< "$SETTINGS")
((${#JOBS[@]})) || {
    echo 'Config has no jobs.' >&2
    exit 1
}
runner=("$@")
if ((!${#runner[@]})); then runner=("$SCRIPT_DIR/backuphelper.sh"); fi
[[ ${runner[0]} = /* && -x ${runner[0]} ]] || {
    echo 'Runner needs an absolute executable path.' >&2
    exit 1
}
runner+=(--config "$CONFIG")
exec_start=''
for argument in "${runner[@]}"; do
    [[ $argument != *$'\n'* && $argument != *$'\r'* ]] || exit 1
    argument=${argument//\\/\\\\}
    argument=${argument//\"/\\\"}
    argument=${argument//%/%%}
    argument=${argument//\$/\$\$}
    exec_start+="\"$argument\" "
done

staging=$(mktemp -d)
trap 'rm -rf -- "$staging"' EXIT
marker='# Generated by backuphelper/install-systemd.sh.'
timers=()
for job in "${JOBS[@]}"; do
    [[ $job =~ ^[A-Za-z0-9][A-Za-z0-9_-]*$ ]] || {
        echo 'Invalid job name.' >&2
        exit 1
    }
    if jq -e --arg job "$job" '.[$job] | has("interval")' <<< "$SETTINGS" > /dev/null; then
        echo "$job: replace interval with schedule before installing timers." >&2
        exit 1
    fi
    schedule=$(jq -r --arg job "$job" '.[$job].schedule // empty' <<< "$SETTINGS")
    [[ -n $schedule ]] || continue
    [[ $schedule != *$'\n'* && $schedule != *$'\r'* ]] || {
        echo "$job: invalid schedule." >&2
        exit 1
    }
    systemd-analyze calendar -- "$schedule" > /dev/null
    timer="backuphelper-$job.timer"
    timers+=("$timer")
    cat > "$staging/$timer" << EOF
$marker
[Unit]
Description=Scheduled backuphelper job $job

[Timer]
OnCalendar=$schedule
Persistent=true
Unit=backuphelper@$job.service

[Install]
WantedBy=timers.target
EOF
done

cat > "$staging/backuphelper@.service" << EOF
$marker
[Unit]
Description=Backuphelper job %i

[Service]
Type=oneshot
User=$RUN_AS
ExecStart=${exec_start}%i
Nice=10
IOSchedulingClass=idle
EOF

systemd-analyze verify "$staging"/*
units=/etc/systemd/system
install -d "$units"
for previous in "$units"/backuphelper-*.timer; do
    grep -qxF "$marker" "$previous" || continue
    if [[ ! -f "$staging/${previous##*/}" ]]; then
        systemctl disable --now "${previous##*/}"
        rm -- "$previous"
    fi
done
install -m 644 "$staging"/* "$units/"
systemctl daemon-reload
if ((${#timers[@]})); then
    systemctl enable "${timers[@]}"
    systemctl restart "${timers[@]}"
fi
printf 'Installed %s persistent backup timer(s).\n' "${#timers[@]}"
